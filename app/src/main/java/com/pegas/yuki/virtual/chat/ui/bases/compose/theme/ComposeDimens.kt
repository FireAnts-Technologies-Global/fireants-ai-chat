// Base design width from Figma
private const val FIGMA_WIDTH = 402f

@Composable
fun getScaledDp(value: Int): Dp {
    val screenWidth = LocalConfiguration.current.screenWidthDp
    return (value * (screenWidth / FIGMA_WIDTH)).dp
}

